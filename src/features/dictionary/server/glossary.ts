const SUFFIX_RULES: [RegExp, string][] = [
  [/ies$/, "y"],
  [/ied$/, "y"],
  [/ing$/, ""],
  [/ing$/, "e"],
  [/ed$/, ""],
  [/ed$/, "e"],
  [/es$/, ""],
  [/s$/, ""],
];

/** Looks up a normalized word, trying simple English inflection rules. */
export function lookupGlossary(word: string): { lemma: string; translation: string } | null {
  if (GLOSSARY[word]) return { lemma: word, translation: GLOSSARY[word] };
  for (const [pattern, replacement] of SUFFIX_RULES) {
    if (!pattern.test(word)) continue;
    const lemma = word.replace(pattern, replacement);
    if (lemma.length > 1 && GLOSSARY[lemma]) return { lemma, translation: GLOSSARY[lemma] };
  }
  return null;
}
